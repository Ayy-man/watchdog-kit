#!/usr/bin/env node
/**
 * scripts/vendor-core.mjs: copy the kit's core/ into a client repo at
 * lib/watchdog/core/ and stamp it, or check an existing copy for drift.
 *
 *   node scripts/vendor-core.mjs <client repo>            copy core/ in, refusing to overwrite locally edited files
 *   node scripts/vendor-core.mjs <client repo> --force    overwrite locally edited files too
 *   node scripts/vendor-core.mjs <client repo> --check    report only; exits 1 when any file is diverged, stale or missing
 *
 * The stamp is <client>/lib/watchdog/core/VENDORED: the kit version (from
 * core/VERSION, or 0.0.0-dev when that file does not exist yet), the kit
 * path and time, and a sha256 per file. "Diverged" means the client's copy
 * no longer matches the hash recorded at vendoring time, so somebody edited
 * it in the client; those files are never overwritten without --force.
 * "Stale" means the client's copy matches its stamp but the kit has moved on.
 */

import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, mkdirSync, writeFileSync, cpSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const kit = dirname(dirname(fileURLToPath(import.meta.url)));
const coreDir = join(kit, 'core');
const args = process.argv.slice(2);
const target = args.find((a) => !a.startsWith('--'));
const check = args.includes('--check');
const force = args.includes('--force');
if (!target) {
  console.error('usage: node scripts/vendor-core.mjs <client repo> [--check] [--force]');
  process.exit(2);
}
const destDir = join(resolve(target), 'lib', 'watchdog', 'core');
const stampPath = join(destDir, 'VENDORED');
const STAMP_NAME = 'VENDORED';

function walk(dir, base = dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.') || name === 'node_modules') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p, base));
    else out.push(relative(base, p).split(sep).join('/'));
  }
  return out;
}
function sha256(p) {
  return createHash('sha256').update(readFileSync(p)).digest('hex');
}
function kitVersion() {
  const v = join(coreDir, 'VERSION');
  return existsSync(v) ? readFileSync(v, 'utf8').trim() : '0.0.0-dev';
}
function readStamp() {
  if (!existsSync(stampPath)) return null;
  const lines = readFileSync(stampPath, 'utf8').split('\n');
  const stamp = { version: null, files: new Map() };
  for (const line of lines) {
    const m = line.match(/^([0-9a-f]{64})  (.+)$/);
    if (m) stamp.files.set(m[2], m[1]);
    const v = line.match(/^watchdog-kit (\S+)/);
    if (v) stamp.version = v[1];
  }
  return stamp;
}
function writeStamp(files) {
  const lines = [
    `watchdog-kit ${kitVersion()}`,
    `source ${coreDir}`,
    `vendored ${new Date().toISOString()}`,
    'sha256 per file; do not edit this file by hand. Check drift with: node scripts/vendor-core.mjs <repo> --check',
    '',
    ...files.map((f) => `${sha256(join(coreDir, f))}  ${f}`),
  ];
  writeFileSync(stampPath, lines.join('\n') + '\n');
}

const kitFiles = walk(coreDir).filter((f) => f !== STAMP_NAME);
const stamp = readStamp();
const destFiles = existsSync(destDir) ? walk(destDir).filter((f) => f !== STAMP_NAME) : [];

const report = { same: [], stale: [], diverged: [], missing: [], extra: [] };
for (const f of kitFiles) {
  const kitHash = sha256(join(coreDir, f));
  const destPath = join(destDir, f);
  if (!existsSync(destPath)) { report.missing.push(f); continue; }
  const destHash = sha256(destPath);
  const recorded = stamp?.files.get(f) ?? null;
  if (destHash === kitHash) report.same.push(f);
  else if (recorded && destHash === recorded) report.stale.push(f);
  else report.diverged.push(f);
}
for (const f of destFiles) if (!kitFiles.includes(f)) report.extra.push(f);

const rel = (f) => `lib/watchdog/core/${f}`;
function printReport() {
  console.log(`kit core ${kitVersion()} at ${coreDir}`);
  console.log(`target   ${destDir}${stamp ? ` (stamped ${stamp.version})` : ' (no VENDORED stamp)'}`);
  const line = (label, list) => { if (list.length) console.log(`${label}\n${list.map((f) => '  ' + rel(f)).join('\n')}`); };
  console.log(`${report.same.length} identical, ${report.stale.length} stale, ${report.diverged.length} diverged, ${report.missing.length} missing, ${report.extra.length} extra`);
  line('diverged (edited in the client since vendoring; kept unless --force):', report.diverged);
  line('stale (unchanged in the client, newer in the kit):', report.stale);
  line('missing (in the kit, not in the client):', report.missing);
  line('extra (in the client, not in the kit; left alone):', report.extra);
}

if (check) {
  const repo = resolve(target);
  console.log(`kit core ${kitVersion()} at ${coreDir}`);
  console.log(`target   ${destDir}${stamp ? ` (stamped ${stamp.version})` : ' (no VENDORED stamp)'}`);
  const fix = {
    missing: `in the kit, not in the client; run node scripts/vendor-core.mjs ${repo}`,
    stale: `unchanged in the client, newer in the kit; run node scripts/vendor-core.mjs ${repo}`,
    diverged: `edited in the client since vendoring; copy the edit back into the kit, or run node scripts/vendor-core.mjs ${repo} --force to drop it`,
  };
  for (const kind of ['diverged', 'stale', 'missing']) {
    for (const f of report[kind]) console.log(`${kind.padEnd(8)} ${rel(f)}  (${fix[kind]})`);
  }
  for (const f of report.extra) console.log(`extra    ${rel(f)}  (in the client, not in the kit; left alone)`);
  const problems = report.diverged.length + report.stale.length + report.missing.length;
  console.log(problems ? `${problems} file(s) out of step with the kit` : `all ${report.same.length} file(s) match the kit`);
  process.exit(problems ? 1 : 0);
}

if (report.diverged.length && !force) {
  printReport();
  console.log('\nrefusing to overwrite diverged files. Re-run with --force to replace them, or copy the client edits back into the kit first.');
  process.exit(1);
}

mkdirSync(destDir, { recursive: true });
const toCopy = [...report.missing, ...report.stale, ...(force ? report.diverged : [])];
for (const f of toCopy) {
  mkdirSync(dirname(join(destDir, f)), { recursive: true });
  cpSync(join(coreDir, f), join(destDir, f));
}
writeStamp(kitFiles);
printReport();
console.log(`\ncopied ${toCopy.length} file(s)${force && report.diverged.length ? ` (${report.diverged.length} overwritten with --force)` : ''}; stamp written to ${stampPath}`);
